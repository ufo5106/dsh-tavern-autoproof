const LOG_MAX_BYTES = 256 * 1024
const LOG_KEEP_BYTES = 100 * 1024

function writeLog(entry) {
  try {
    const line = JSON.stringify({ ts: new Date().toISOString(), ...entry }) + '\n'
    try {
      const stat = fs.statSync(LOG_PATH)
      if (stat.size > LOG_MAX_BYTES) {
        const fd = fs.openSync(LOG_PATH, 'r')
        try {
          const start = Math.max(0, stat.size - LOG_KEEP_BYTES)
          const buf = Buffer.allocUnsafe(stat.size - start)
          fs.readSync(fd, buf, 0, buf.length, start)
          const text = buf.toString('utf8')
          const nl = text.indexOf('\n')
          fs.writeFileSync(LOG_PATH, nl >= 0 ? text.slice(nl + 1) : text, 'utf8')
        } finally {
          fs.closeSync(fd)
        }
      }
    } catch {
      // ignore stat/rotation errors when log file does not exist yet
    }
    fs.appendFileSync(LOG_PATH, line, 'utf8')
  } catch {
    // 忽略日誌寫入失敗，避免影響宿主執行
  }
}

