const HTML_ELEMENTS = new Set(('html head body title base link meta style script noscript template slot ' +
  'address article aside footer header h1 h2 h3 h4 h5 h6 hgroup main nav search section ' +
  'blockquote dd div dl dt figcaption figure hr li menu ol p pre ul a abbr b bdi bdo br cite code data dfn em i kbd mark q rp rt ruby s samp small span strong sub sup time u var wbr ' +
  'area audio img map track video embed iframe object picture source canvas svg math portal ' +
  'del ins caption col colgroup table tbody td tfoot th thead tr button datalist fieldset form input label legend meter optgroup option output progress select textarea ' +
  'details dialog summary acronym applet big center dir font frame frameset marquee noframes param strike tt xmp').split(' '))

const VOID_TAGS = new Set('area base br col embed hr img input link meta param source track wbr'.split(' '))

function isNarrativeTag(tag, token) {
  return tag && !HTML_ELEMENTS.has(tag) && !/[-:]/.test(tag) && /^<\/?[a-z][\w]*\s*\/?\s*>$/i.test(token)
}

function isHtmlFenceSource(value, info = '') {
  const content = String(value ?? '')
  const language = String(info ?? '').trim().split(/\s+/, 1)[0].toLowerCase()
  if (language === 'text') {
    if (/^\s*(?:<!doctype\s+html\s*>\s*)?<html(?:\s[^<>]*?)?>[\s\S]*<\/html>\s*$/i.test(content)) return true
    return /^\s*<body(?:\s[^<>]*?)?>[\s\S]*<\/body>\s*$/i.test(content)
      && /<(?:script|iframe|object|embed)\b/i.test(content)
  }
  if (language !== '') return language === 'html' || language === 'htm'
  return /html>|<head>|<body/i.test(content)
}

function fencedSegments(value) {
  const lines = String(value ?? '').match(/.*(?:\r?\n|$)/g) || []
  const segments = []
  let plain = ''
  let fence = null
  let fenced = ''
  let content = ''
  for (const line of lines) {
    const bare = line.replace(/\r?\n$/, '')
    if (fence === null) {
      const opening = bare.match(/^[ \t]{0,3}(`{3,}|~{3,})([^\r\n]*)$/)
      if (opening !== null) {
        fence = { character: opening[1][0], length: opening[1].length, info: opening[2] }
        fenced = line
        content = ''
      } else {
        plain += line
      }
      continue
    }
    fenced += line
    const closing = bare.match(/^[ \t]{0,3}(`+|~+)[ \t]*$/)
    if (closing !== null && closing[1][0] === fence.character && closing[1].length >= fence.length) {
      if (isHtmlFenceSource(content, fence.info)) {
        if (plain !== '') segments.push({ kind: 'text', text: plain })
        segments.push({ kind: 'html', text: fenced, fenced: true })
        plain = ''
      } else {
        // 非 HTML 圍欄（如 ```js / ```text）：宿主視為 text，但插件標記為 code 以免 Tier1/Tier2 誤改程式碼範例
        if (plain !== '') segments.push({ kind: 'text', text: plain })
        segments.push({ kind: 'code', text: fenced })
        plain = ''
      }
      fence = null
      fenced = ''
      content = ''
      continue
    }
    content += line
  }
  if (fence !== null) plain += fenced
  if (plain !== '') segments.push({ kind: 'text', text: plain })
  return segments
}

function splitHtmlBoundariesEditing(source) {
  const segments = []
  const stack = []
  const tokens = /<!--[\s\S]*?(?:-->|$)|<!doctype\b[^>]*>|<\/?([a-z][\w:-]*)\b(?:"[^"]*"|'[^']*'|[^'">])*?>|(`+)[\s\S]*?\2/gi
  let cursor = 0
  let start = -1
  function append(kind, value) {
    if (!value) return
    const previous = segments[segments.length - 1]
    if (previous && (previous.kind === kind || !value.trim())) {
      previous.text += value
    } else {
      segments.push({ kind, text: value })
    }
  }
  let token
  while ((token = tokens.exec(source))) {
    if (token[2]) continue // 行內反引號代碼不視為可執行 HTML
    const tag = (token[1] || '').toLowerCase()
    const closing = /^<\//.test(token[0])
    if (isNarrativeTag(tag, token[0])) {
      if (start < 0) {
        append('text', source.slice(cursor, token.index))
        append('text', token[0])
        cursor = tokens.lastIndex
      }
      continue
    }
    if (start < 0) {
      append('text', source.slice(cursor, token.index))
      start = token.index
    }
    if (closing) {
      const index = stack.lastIndexOf(tag)
      if (index >= 0) stack.length = index
    } else if (tag && !VOID_TAGS.has(tag) && !/\/\s*>$/.test(token[0])) {
      stack.push(tag)
      if (['script', 'style', 'textarea', 'title'].includes(tag)) {
        const end = new RegExp('</' + tag + '\\s*>', 'gi')
        end.lastIndex = tokens.lastIndex
        const match = end.exec(source)
        if (!match) { tokens.lastIndex = source.length; break }
        tokens.lastIndex = end.lastIndex
        stack.pop()
      }
    }
    if (!stack.length) {
      append('html', source.slice(start, tokens.lastIndex))
      cursor = tokens.lastIndex
      start = -1
    }
  }
  if (start >= 0) append('html', source.slice(start))
  else append('text', source.slice(cursor))
  return segments
}

export function editableParts(rawText) {
  const source = String(rawText ?? '')
  const out = []
  for (const seg of fencedSegments(source)) {
    if (seg.kind === 'html') {
      out.push({ kind: 'html', text: seg.text, fenced: true })
    } else if (seg.kind === 'code') {
      out.push({ kind: 'code', text: seg.text })
    } else {
      out.push(...splitHtmlBoundariesEditing(seg.text))
    }
  }
  return out
}

export function findProtectedSpans(source) {
  const s = String(source ?? '')
  const spans = []
  let offset = 0
  for (const part of editableParts(s)) {
    const len = part.text.length
    if (part.kind === 'html') spans.push([offset, offset + len])
    offset += len
  }
  return spans
}

export function tagTokens(text) {
  return String(text ?? '').match(/<\/?[A-Za-z_][\w:.~-]*(?:\s[^>]*)?\/?>/g) || []
}

export function diffTags(rawA, rawB) {
  const aHtml = editableParts(rawA).filter(p => p.kind === 'html')
  const bHtml = editableParts(rawB).filter(p => p.kind === 'html')
  if (aHtml.length !== bHtml.length) return `HTML 區塊數 ${aHtml.length}→${bHtml.length}`
  for (let i = 0; i < aHtml.length; i++) {
    if (aHtml[i].text.trim() !== bHtml[i].text.trim()) {
      return `第 ${i + 1} 個 HTML 區塊與原文不一致`
    }
  }
  return ''
}

// 寫回前的硬校驗：對齊宿主 body-editor.js replaceText 的比對規則
export function diffProtected(rawA, rawB) {
  const a = editableParts(rawA).filter(p => p.kind === 'html')
  const b = editableParts(rawB).filter(p => p.kind === 'html')
  if (a.length !== b.length) return `HTML 區段數量 ${a.length}→${b.length}`
  for (let i = 0; i < a.length; i++) {
    if (a[i].text.trim() !== b[i].text.trim()) {
      let k = 0
      while (k < a[i].text.length && k < b[i].text.length && a[i].text[k] === b[i].text[k]) k++
      return `第 ${i + 1} 個 HTML 區段在第 ${k} 字符處不同：「${a[i].text.slice(k, k + 20)}」→「${b[i].text.slice(k, k + 20)}」`
    }
  }
  return ''
}

function gapsOf(text, spans) {
  const gaps = []
  let cursor = 0
  for (const [s, e] of spans) { gaps.push([cursor, s]); cursor = e }
  gaps.push([cursor, text.length])
  return gaps
}

// 搶救式重拼：文字區用改寫後的內容，保護區位元組級取回原文
export function rebuildKeepingProtected(raw, rewritten) {
  const rawSpans = findProtectedSpans(raw)
  const finSpans = findProtectedSpans(rewritten)
  if (rawSpans.length !== finSpans.length) return null
  const rawGaps = gapsOf(raw, rawSpans)
  const finGaps = gapsOf(rewritten, finSpans)
  let out = ''
  for (let i = 0; i < rawSpans.length; i++) {
    out += String(rewritten).slice(finGaps[i][0], finGaps[i][1])
    out += String(raw).slice(rawSpans[i][0], rawSpans[i][1])
  }
  out += String(rewritten).slice(finGaps[finGaps.length - 1][0])
  return out
}

export function splitSegments(rawText) {
  const parts = editableParts(rawText)
  if (!parts.length) return [{ type: 'text', content: '' }]
  return parts.map(p => ({
    type: p.kind === 'html' ? 'html' : (p.kind === 'code' ? 'code' : 'text'),
    content: p.text,
  }))
}

export function reassemble(segs) {
  return segs.map(seg => (seg.type === 'text' && seg.rewrite != null ? seg.rewrite : seg.content)).join('')
}

function hanzi(str) {
  const m = String(str ?? '').match(/[\u4e00-\u9fff]/g)
  return m ? m.length : 0
}

// ---- 正面保護規則：避免誤改優秀短句、角色特色對話與有效懸念 ----

export function isProtectedLine(line) {
  const trimmed = String(line ?? '').trim()
  if (!trimmed) return true

  // 1. 簡潔有力的懸疑／節奏定格短句（≤14 漢字且不含翻案轉折或帳本腔）
  if (
    hanzi(trimmed) <= 14 &&
    !/(?:而是|與其|与其|但是|不過|不过|小本本|一[笔筆]|算你)/.test(trimmed) &&
    !/得很有|得[极極]/.test(trimmed) &&
    /[。！？]$/.test(trimmed)
  ) {
    return true
  }

  // 2. 純對話短句（例如：「幾丈。」「都別下去。」藍忘機道。）
  if (/^[「『“][^」』”]{1,28}[」』”](?:[\u4e00-\u9fff]{1,6}道[。！]?)?$/.test(trimmed)) {
    return true
  }

  // 3. 對話搭配簡短神態／互動（≤45 漢字且不含帳本化、神情分類或頂真拆解）
  if (
    hanzi(trimmed) <= 45 &&
    /[「『“][^」』”]{1,28}[」』”]/.test(trimmed) &&
    !/(?:而是|小本本|算你|一[笔筆]|先是?一[种種]|的那[种種]|客[气氣][三五]分)/.test(trimmed) &&
    !/([\u4e00-\u9fff]{2})[了着著][^，。！？\n]{0,6}[，,][^。！？\n]{0,4}\1/.test(trimmed)
  ) {
    return true
  }

  return false
}

