// 計算全文與 500 字窗口內的廣義對舉／否定揭示密度
export function analyzeNarrativeStructure(text) {
  const source = String(text ?? '')
  const totalHanzi = Math.max(1, hanzi(source))

  // 廣義對舉句式（含「不是A，是B」「不是躺著的。\n是一具…」「並非…而是…」「與其…不如…」）
  const broadAntithesisRe = /(?:不是[^，。！？\n]{1,22}[，。]\s*(?:是|而是|是一具)|(?:並非|并非|與其說|与其说)[^。！？\n]{1,28}(?:而是|不如說|不如说)|「她不是沉下去的。」)/g
  const antithesisMatches = [...source.matchAll(broadAntithesisRe)].map(m => ({
    text: m[0],
    index: m.index || 0,
  }))

  // 500 字滑動窗口最高對舉數
  let maxAntithesisIn500 = 0
  for (let i = 0; i < antithesisMatches.length; i++) {
    let count = 1
    for (let j = i + 1; j < antithesisMatches.length; j++) {
      if (antithesisMatches[j].index - antithesisMatches[i].index <= 500) count++
    }
    if (count > maxAntithesisIn500) maxAntithesisIn500 = count
  }

  // 350 字滑動窗口內的「一X一X」或「X了一X」疊詞量詞密度
  const redupRe = /(?:一[片道條叢鼓根串步丈]一[片道條叢鼓根串步丈]|([\u4e00-\u9fff])了一\1)/g
  const redupMatches = [...source.matchAll(redupRe)].map(m => ({
    text: m[0],
    index: m.index || 0,
  }))
  let maxRedupIn350 = 0
  for (let i = 0; i < redupMatches.length; i++) {
    let count = 1
    for (let j = i + 1; j < redupMatches.length; j++) {
      if (redupMatches[j].index - redupMatches[i].index <= 350) count++
    }
    if (count > maxRedupIn350) maxRedupIn350 = count
  }

  // 動作膨脹／頂真拆解次數
  const actionEchoRe = /(?:([\u4e00-\u9fff]{1,2})了(?:\1|兩下|幾筆|個面|半步)[，,]\s*\1|飄起來[，,]飄到一半|掃得一片一片朝下翻卷[，,]翻卷過的磚面上留著一道一道的白痕[，,]白痕在黑暗[裡里]一條一條往上退)/g
  const actionEchoMatches = [...source.matchAll(actionEchoRe)].map(m => m[0])

  // 對話段落配動作比例
  const paras = source.split(/\n+/).map(s => s.trim()).filter(Boolean)
  const dialogueParas = paras.filter(p => /[「『“][^」』”]+[」』”]/.test(p))
  const stageGestureRe = /(?:低頭|抬頭|蹲下|站起|轉身|扣住|把背貼|把袖子|往身後一拉|雙手[遞递]|拱手|拔劍|伸手)/
  const dialogueWithStage = dialogueParas.filter(p => stageGestureRe.test(p))
  const dialogueActionRatio = dialogueParas.length
    ? Number((dialogueWithStage.length / dialogueParas.length).toFixed(2))
    : 0

  return {
    totalHanzi,
    antithesisCount: antithesisMatches.length,
    antithesisDensityPer500: Number(((antithesisMatches.length / totalHanzi) * 500).toFixed(2)),
    maxAntithesisIn500,
    antithesisSamples: antithesisMatches.map(m => m.text.replace(/\s+/g, ' ').slice(0, 32)),
    redupCount: redupMatches.length,
    maxRedupIn350,
    redupSamples: redupMatches.map(m => m.text),
    actionEchoCount: actionEchoMatches.length,
    actionEchoSamples: actionEchoMatches.map(s => s.slice(0, 36)),
    dialogueParasCount: dialogueParas.length,
    dialogueWithStageCount: dialogueWithStage.length,
    dialogueActionRatio,
  }
}

export function candidateKeys(text, options = {}) {
  const source = String(text ?? '')
  if (options.respectProtection && isProtectedLine(source)) {
    return []
  }
  const found = []
  for (const rule of [...REWRITE_CANDIDATES, ...RECURRING_CANDIDATES]) {
    rule.re.lastIndex = 0
    if (rule.re.test(source)) found.push(rule.key)
  }
  return found
}

