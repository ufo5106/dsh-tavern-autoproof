// 偵測人物卡本身的簡繁傾向（用於「跟隨人物卡」auto 模式）
export function detectCardScript(card) {
  if (!card || typeof card !== 'object') return 'trad'
  const chunks = [card.description, card.personality, card.scenario, card.first_mes]
  const rawEntries = card.character_book?.entries
  const entries = Array.isArray(rawEntries)
    ? rawEntries
    : (rawEntries && typeof rawEntries === 'object' ? Object.values(rawEntries) : [])
  for (const entry of entries.slice(0, 6)) {
    if (entry && typeof entry.content === 'string') chunks.push(entry.content)
  }
  const sample = chunks.filter(Boolean).join('\n')
  if (!sample) return 'trad'
  let simp = 0
  let trad = 0
  for (const ch of sample) {
    const s2t = CHAR_FIXES[ch]
    const t2s = CHAR_FIXES_T2S[ch]
    if (s2t && !t2s) simp++
    else if (t2s && !s2t) trad++
  }
  if (simp > trad * 1.5 && simp >= 8) return 'simp'
  return 'trad'
}

// 讀取人物卡世界書中的【文風基準】條目（可選 JSON 閾值覆蓋 + 文風提示）
export function readCardStyleSpec(card) {
  if (!card || typeof card !== 'object') return { limits: null, styleGuide: '' }
  const rawEntries = card.character_book?.entries
  const entries = Array.isArray(rawEntries)
    ? rawEntries
    : (rawEntries && typeof rawEntries === 'object' ? Object.values(rawEntries) : [])
  const hit = entries.find((e) => {
    if (!e || e.enabled === false) return false
    const label = [e.comment, e.name, e.title, ...(Array.isArray(e.keys) ? e.keys : [])].filter(Boolean).join(' ')
    return /文風基準|文风基准/.test(label)
  })
  if (!hit || typeof hit.content !== 'string' || !hit.content.trim()) {
    return { limits: null, styleGuide: '' }
  }
  let limits = null
  const jsonMatch = hit.content.match(/```json\s*([\s\S]*?)```/i)
  if (jsonMatch) {
    try {
      const parsed = JSON.parse(jsonMatch[1])
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) limits = parsed
    } catch {
      // ignore invalid JSON block
    }
  }
  const styleGuide = hit.content.replace(/```json[\s\S]*?```/gi, '').trim().slice(0, 800)
  return { limits, styleGuide }
}

// 跨輪次生成前輕量文體提醒（供 turnSection 注入，避免模型從一開始進入模板化寫作）
export function buildTurnConstraintHint(recurringKeys = [], mode = 'standard', extra = {}) {
  const { cooldownWords = [], structuralFlags = [], includeStyleHints = true } = extra
  const hints = []
  if (includeStyleHints && (recurringKeys.length || mode !== 'conservative')) {
    if (recurringKeys.includes('paired_reversal') || recurringKeys.includes('omitted_antithesis')) {
      hints.push('避免反覆使用「不是A，而是/是B」的否定揭示句式，多數場景事實請直接正面敘述。')
    }
    if (recurringKeys.includes('action_inflation') || recurringKeys.includes('soft_dialogue_stage')) {
      hints.push('人物動作只在具劇情或人物關係意義時描寫，避免「做了A，A得如何」的頂真拆解，也不必每句對話都配低頭、抬頭等舞台動作。')
    }
    if (recurringKeys.includes('reduplication_cluster')) {
      hints.push('控制「一X一X」疊詞量詞密度，避免同一段內連續堆疊三組以上相同節奏的量詞。')
    }
    if (recurringKeys.includes('soft_suspense_escalation')) {
      hints.push('注意敘事節奏呼吸，不必在每個小節結尾都套用「發現異常→人物反應→更大異常」的加碼公式，允許自然的人物交流與情緒緩衝。')
    }
  }
  if (Array.isArray(cooldownWords) && cooldownWords.length > 0) {
    hints.push(`【高頻動作／意象冷卻】最近幾輪已重複出現「${cooldownWords.slice(0, 5).join('、')}」，本輪請改用其他具體感官或動作描寫，暫時避開上述詞彙。`)
  }
  if (Array.isArray(structuralFlags) && structuralFlags.length > 0) {
    if (structuralFlags.includes('tidy_ending')) {
      hints.push('【敘事結構提醒】最近多輪均以「心理頓悟／說教總結」收尾；本輪結尾請嘗試直接停在具體動作、環境小質感或對話上，不強行總結。')
    }
    if (structuralFlags.includes('flat_pacing')) {
      hints.push('【節奏變化提醒】最近多輪段長與句長偏均勻，請依場景張力錯落安排長短句與段落呼吸。')
    }
    if (structuralFlags.includes('telling_heavy')) {
      hints.push('【感官具象提醒】最近多輪情緒偏向直接心理說明，請多用具體觸覺、溫度、聲音或空間動作來代替抽象心理詞。')
    }
    if (structuralFlags.includes('dialogue_sandwich')) {
      hints.push('【對話自然度提醒】近期出現多段「『台詞』＋插入動作＋『台詞』」三明治格式或「語氣很平，手卻…」反差模板；對話請直接自然接話，不需每句都配微動作，也避免對隊友複誦人盡皆知的背景設定。')
    }
    if (structuralFlags.includes('verb_triple_parallel')) {
      hints.push('【句型去公式提醒】減少「動詞A，動詞B，動詞C」三連排比與對仗格言短句，改用更自然口語的節奏表達。')
    }
  }
  if (!hints.length) return ''
  return `【敘事文體微調提醒（AutoProof）】\n${hints.slice(0, 7).map(h => `- ${h}`).join('\n')}`
}

// v1.28：模型输出清洗——去掉围栏、开头的编号、没头没脑的引导语，只留正文
export function cleanModelText(s) {
  let t = String(s ?? '').trim()
  t = t.replace(/^\s*```[a-zA-Z]*\s*\n?/, '').replace(/\n?```\s*$/, '')
  t = t.replace(/^\s*\[\d+\]\s*/, '')
  t = t.replace(/^\s*(?:改寫|改写|校對後|校对后|結果|结果|以下是)[^\n]{0,12}[：:]\s*\n?/, '')
  return t.trim()
}

// 并发池：一次只跑 limit 个，失败不影响其他段
async function poolMap(items, limit, fn) {
  const out = new Array(items.length)
  let next = 0
  const runners = Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, async () => {
    for (;;) {
      const i = next++
      if (i >= items.length) return
      out[i] = await fn(items[i], i)
    }
  })
  await Promise.all(runners)
  return out
}

