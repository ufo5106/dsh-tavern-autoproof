export function applyCharFixes(input, options = {}) {
  const enablePhrases = options.enablePhrases !== false
  // v1.23：字形方向。trad＝簡轉繁（預設）／simp＝繁轉簡／keep＝只修詞組與英文，不動字形
  const toScript = options.toScript || 'trad'
  let text = String(input ?? '')
  const fixCounts = new Map()
  const fixTargets = new Map()

  const recordFix = (from, to, delta = 1) => {
    fixCounts.set(from, (fixCounts.get(from) || 0) + delta)
    fixTargets.set(from, to)
  }

  // 1. 先執行上下文詞組修正（簡體模式下只套用漏字類，簡→繁字形規則跳過）
  if (enablePhrases) {
    for (const rule of PHRASE_FIXES) {
      if (toScript === 'simp' && rule.kind !== 'typo') continue
      if (!text.includes(rule.from)) continue
      const parts = text.split(rule.from)
      const count = parts.length - 1
      if (count > 0) {
        text = parts.join(rule.to)
        recordFix(rule.from, rule.to, count)
      }
    }
  }

  if (enablePhrases) {
    // 針對緊鄰中文字的孤立小寫英文單詞做安全替換
    const strayMap = toScript === 'simp' ? CJK_STRAY_WORD_MAP_SIMP : CJK_STRAY_WORD_MAP
    text = text.replace(/([\u4e00-\u9fff])\s*([a-z]{3,10})\s*([\u4e00-\u9fff，。！？、])/g, (full, pre, word, post) => {
      const replacement = strayMap[word.toLowerCase()]
      if (!replacement) return full
      recordFix(word, replacement, 1)
      return `${pre}${replacement}${post}`
    })
    // 修復中文字之間誤夾的英文半形逗號（如「位置,便」）
    text = text.replace(/([\u4e00-\u9fff]),([\u4e00-\u9fff])/g, (_, pre, post) => {
      recordFix(',', '，', 1)
      return `${pre}，${post}`
    })
  }

  // 2. 單字級字形轉換（預設簡→繁；simp 用反向表；keep 不動字形）
  const table = toScript === 'simp' ? CHAR_FIXES_T2S_FULL : (toScript === 'keep' ? null : CHAR_FIXES)
  let out = ''
  for (const ch of text) {
    const mapped = table ? table[ch] : undefined
    if (mapped) {
      out += mapped
      recordFix(ch, mapped, 1)
    } else {
      out += ch
    }
  }

  const list = Array.from(fixCounts.entries()).map(([from, count]) => ({
    from,
    to: fixTargets.get(from) || (table ? table[from] : undefined),
    count,
  }))
  const total = list.reduce((sum, item) => sum + item.count, 0)
  return { text: out, fixes: list, total }
}

